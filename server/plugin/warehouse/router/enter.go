// Package router owns warehouse route registration.
package router

import (
	"github.com/flipped-aurora/gin-vue-admin/server/plugin/warehouse/api"
	"github.com/gin-gonic/gin"
)

var Router = new(router)

type router struct{}

func (r *router) Init(group *gin.RouterGroup) {
	master := group.Group("/master")
	handler := api.DefaultMasterAPI()
	units := master.Group("/units")
	units.GET("/list", handler.ListUnits)
	units.GET("/detail", handler.UnitDetail)
	units.POST("/create", handler.CreateUnit)
	units.PUT("/update", handler.UpdateUnit)
	units.DELETE("/delete", handler.DeleteUnit)
	units.GET("/template", handler.MasterTemplate("units"))
	units.POST("/import", handler.MasterImport("units"))
	units.GET("/export", handler.MasterExport("units"))
	brands := master.Group("/brands")
	brands.GET("/list", handler.ListBrands)
	brands.GET("/detail", handler.BrandDetail)
	brands.POST("/create", handler.CreateBrand)
	brands.PUT("/update", handler.UpdateBrand)
	brands.DELETE("/delete", handler.DeleteBrand)
	brands.GET("/template", handler.MasterTemplate("brands"))
	brands.POST("/import", handler.MasterImport("brands"))
	brands.GET("/export", handler.MasterExport("brands"))
	categories := master.Group("/categories")
	categories.GET("/list", handler.ListCategories)
	categories.GET("/detail", handler.CategoryDetail)
	categories.GET("/tree", handler.CategoryTree)
	categories.POST("/create", handler.CreateCategory)
	categories.PUT("/update", handler.UpdateCategory)
	categories.DELETE("/delete", handler.DeleteCategory)
	categories.GET("/template", handler.MasterTemplate("categories"))
	categories.POST("/import", handler.MasterImport("categories"))
	categories.GET("/export", handler.MasterExport("categories"))
	materials := master.Group("/materials")
	materials.GET("/list", handler.ListMaterials)
	materials.GET("/detail", handler.MaterialDetail)
	materials.POST("/create", handler.CreateMaterial)
	materials.PUT("/update", handler.UpdateMaterial)
	materials.DELETE("/delete", handler.DeleteMaterial)
	materials.POST("/uploadImage", handler.UploadMaterialImage)
	materials.GET("/template", handler.MasterTemplate("materials"))
	materials.POST("/import", handler.MasterImport("materials"))
	materials.GET("/export", handler.MasterExport("materials"))
	master.POST("/mnemonic", handler.SuggestMnemonic)
	delivery := group.Group("/delivery")
	deliveryHandler := api.DefaultDeliveryAPI()
	delivery.POST("/reserveNumber", deliveryHandler.ReserveNumber)
	delivery.GET("/departments", deliveryHandler.Departments)
	delivery.GET("/list", deliveryHandler.List)
	delivery.GET("/detail", deliveryHandler.Detail)
	delivery.POST("/create", deliveryHandler.Create)
	delivery.PUT("/update", deliveryHandler.Update)
	delivery.DELETE("/delete", deliveryHandler.Delete)
	delivery.POST("/review", deliveryHandler.Review)
	delivery.POST("/unreview", deliveryHandler.Unreview)
	report := group.Group("/reconciliation")
	reportHandler := api.DefaultReconciliationAPI()
	report.GET("/columns", reportHandler.Columns)
	report.GET("/options", reportHandler.Options)
	report.POST("/query", reportHandler.Query)
	report.POST("/export", reportHandler.Export)
	report.POST("/printData", reportHandler.PrintData)
	schemes := group.Group("/schemes")
	schemes.GET("/list", reportHandler.SchemeList)
	schemes.GET("/detail", reportHandler.SchemeDetail)
	schemes.POST("/create", reportHandler.SchemeCreate)
	schemes.PUT("/update", reportHandler.SchemeUpdate)
	schemes.DELETE("/delete", reportHandler.SchemeDelete)
	schemes.POST("/publish", reportHandler.SchemePublish)
}
